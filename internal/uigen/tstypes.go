package uigen

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/tycheg/reasonr-compiler/internal/model"
)

// TypeScript prints the interfaces of primitive implementations for the web
// (RFC §22.7; RFC §22): reasonr build --ui-types. The
// model is not in them; the runtime has already substituted the values:
//
//   - binding: data (a query), submit (a command), value (a field), value
//     and onChange (an input), go (a screen);
//   - parameters: simple ones are values, queries are functions that call
//     the query on the server, field is a row function, screen a transition;
//   - children and parts: labeled elements are nodes or, for row parts,
//     functions that render a row (Item, RowItem);
//   - events: on<Name>;
//   - caption is the node label; rr are labels for UI tests (RFC §22.10).
//
// The model's value objects and enums are interfaces and string unions in
// canonical JSON (RFC §31.3).
func TypeScript(u *model.UI) string {
	var b strings.Builder
	b.WriteString("// Generated by reasonr build --ui-types: interfaces of primitive implementations.\n")
	b.WriteString("// Do not edit by hand.\n\n")
	b.WriteString(`import type { Item, Page, RowItem, RR } from "@tycheg/reasonr-runtime";` + "\n")
	g := &tsGen{u: u, names: tsNames(u)}
	for _, t := range u.Types {
		b.WriteString("\n")
		g.typ(&b, t)
	}
	for _, p := range u.Primitives {
		b.WriteString("\n")
		g.primitive(&b, p)
	}
	return b.String()
}

type tsGen struct {
	u     *model.UI
	vars  map[string]bool   // type variables of the current primitive
	names map[string]string // model type name → TypeScript identifier
}

// tsNames gives model types TypeScript identifiers: the short name (Money
// for Ordering.Money) if it is unique, otherwise the full name joined by "_".
func tsNames(u *model.UI) map[string]string {
	count := map[string]int{}
	short := func(name string) string { return name[strings.LastIndex(name, ".")+1:] }
	for _, t := range u.Types {
		count[short(t.Name)]++
	}
	out := map[string]string{}
	for _, t := range u.Types {
		if count[short(t.Name)] == 1 {
			out[t.Name] = short(t.Name)
		} else {
			out[t.Name] = strings.ReplaceAll(t.Name, ".", "_")
		}
	}
	return out
}

func (g *tsGen) typ(b *strings.Builder, t model.UIType) {
	if len(t.Values) > 0 {
		var vals []string
		for _, v := range t.Values {
			vals = append(vals, fmt.Sprintf("%q", v))
		}
		fmt.Fprintf(b, "export type %s = %s;\n", g.names[t.Name], strings.Join(vals, " | "))
		return
	}
	fmt.Fprintf(b, "export interface %s {\n", g.names[t.Name])
	for _, f := range t.Fields {
		fmt.Fprintf(b, "  %s: %s;\n", f.Name, g.ts(f.Type))
	}
	b.WriteString("}\n")
}

func (g *tsGen) primitive(b *strings.Builder, p model.UIPrimitive) {
	g.vars = map[string]bool{}
	var vars []string
	for _, v := range p.Vars {
		g.vars[v.Name] = true
		vars = append(vars, v.Name)
	}
	generic := ""
	if len(vars) > 0 {
		generic = "<" + strings.Join(vars, ", ") + ">"
	}
	fmt.Fprintf(b, "export interface %sProps%s {\n", p.Name, generic)
	switch p.Binds {
	case "query":
		if strings.HasPrefix(p.BindType, "page<") || strings.Contains(p.BindType, "| page<") {
			fmt.Fprintf(b, "  data: %s;\n", g.ts(p.BindType))
			b.WriteString("  loadMore(): void;\n  hasMore: boolean;\n")
		} else {
			fmt.Fprintf(b, "  data: %s;\n", g.ts(p.BindType))
		}
		b.WriteString("  loading: boolean;\n")
	case "command":
		b.WriteString("  submit(): Promise<boolean>;\n  busy: boolean;\n  errors: string[];\n")
	case "field":
		fmt.Fprintf(b, "  value: %s;\n", g.ts(p.BindType))
	case "input":
		fmt.Fprintf(b, "  value: %s;\n", g.ts(p.BindType))
		fmt.Fprintf(b, "  onChange(value: %s): void;\n", g.ts(p.BindType))
		b.WriteString("  error?: string;\n")
	case "screen":
		b.WriteString("  href: string;\n  go(): void;\n")
	}
	b.WriteString("  caption?: string;\n")
	for _, pp := range p.Params {
		opt := ""
		if pp.Optional && !pp.Auto && pp.Kind != "value" {
			opt = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", pp.Name, opt, g.param(pp))
	}
	if p.Children != nil {
		fmt.Fprintf(b, "  children: %s;\n", g.part(p, *p.Children))
	}
	for _, pt := range p.Parts {
		fmt.Fprintf(b, "  %s: %s;\n", lowerCamel(pt.Name), g.part(p, pt))
	}
	for _, e := range p.Events {
		var params []string
		for _, prm := range e.Params {
			params = append(params, prm.Name+": "+g.ts(prm.Type))
		}
		fmt.Fprintf(b, "  on%s(%s): void;\n", upperFirst(e.Name), strings.Join(params, ", "))
	}
	b.WriteString("  rr: RR;\n}\n")
}

func (g *tsGen) param(pp model.UIPrimParam) string {
	switch pp.Kind {
	case "query":
		return "() => Promise<" + g.ts(pp.Type) + ">"
	case "search":
		var args []string
		for _, v := range pp.Provided {
			args = append(args, v.Name+": "+g.ts(v.Type))
		}
		return "(" + strings.Join(args, ", ") + ") => Promise<" + g.ts(pp.Type) + ">"
	case "field":
		out := "string"
		if pp.FieldType != "" {
			out = g.ts(pp.FieldType)
		}
		return "(row: " + g.ts(pp.Record) + ") => " + out
	case "screen":
		return "() => void"
	}
	return g.ts(pp.Type)
}

// part is children or a part: labeled elements; for a row part of a bound
// page or list, an element renders a row.
func (g *tsGen) part(p model.UIPrimitive, pt model.UIPart) string {
	if pt.Binds == "type" && g.vars[pt.Type] && (strings.Contains(p.BindType, "page<"+pt.Type+">") || strings.Contains(p.BindType, "list<"+pt.Type+">")) {
		return "RowItem<" + pt.Type + ">[]"
	}
	return "Item[]"
}

// ts converts a language type into a TypeScript type of canonical JSON.
func (g *tsGen) ts(t string) string {
	t = strings.TrimSpace(t)
	if alts := splitTop(t, '|'); len(alts) > 1 {
		var out []string
		for _, a := range alts {
			out = append(out, g.ts(a))
		}
		return strings.Join(out, " | ")
	}
	if strings.HasSuffix(t, "?") {
		return g.ts(strings.TrimSuffix(t, "?")) + " | null"
	}
	if i := strings.IndexByte(t, '<'); i > 0 && strings.HasSuffix(t, ">") {
		args := splitTop(t[i+1:len(t)-1], ',')
		switch t[:i] {
		case "list", "set":
			return "Array<" + g.ts(args[0]) + ">"
		case "page":
			return "Page<" + g.ts(args[0]) + ">"
		case "map":
			if len(args) == 2 {
				return "Record<string, " + g.ts(args[1]) + ">"
			}
		}
		return "unknown"
	}
	switch t {
	case "int", "float":
		return "number"
	case "bool":
		return "boolean"
	case "string", "bigint", "decimal", "uuid", "date", "time", "timestamp", "duration", "bytes", "Timer.Id", "id":
		return "string"
	case "enum":
		return "string"
	case "value":
		return "Record<string, unknown>"
	case "PageRequest":
		return "{ size: number; cursor: string | null }"
	}
	if strings.HasSuffix(t, ".Id") || g.vars[t] {
		if g.vars[t] {
			return t
		}
		return "string"
	}
	if g.u.Type(t) != nil {
		return g.names[t]
	}
	return "unknown"
}

// splitTop splits text by a separator outside angle brackets.
func splitTop(s string, sep byte) []string {
	var out []string
	depth, start := 0, 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '<':
			depth++
		case '>':
			depth--
		case sep:
			if depth == 0 {
				out = append(out, strings.TrimSpace(s[start:i]))
				start = i + 1
			}
		}
	}
	return append(out, strings.TrimSpace(s[start:]))
}

func lowerCamel(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
